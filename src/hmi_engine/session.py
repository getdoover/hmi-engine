"""Bring up the graphics session: seatd, then the compositor, then the page.

The container carries its own compositor because the devices this runs on
generally have none — no X, no Wayland, often no GPU userspace at all. sway is
used rather than a smaller kiosk compositor purely because it is the one that
can pin an output mode, which is what lets a 1080p panel be driven at 720p to
save a software renderer a lot of work.

Where the host *does* have a compositor — a Raspberry Pi that has autologged
into labwc — starting a second one is not an option: it cannot get DRM master
and dies on a five-second loop. There the browser attaches to the host's
session instead and this module supervises just that one process.
"""

from __future__ import annotations

import asyncio
import logging
import os
import shlex
import shutil
import signal
from pathlib import Path

from .display import Display, HostCompositor, Mode

log = logging.getLogger(__name__)

RUNTIME_DIR = Path("/tmp/hmi-runtime")
CONFIG_PATH = RUNTIME_DIR / "sway.conf"
#: Where the browser appends its `HMI-STATUS` lines for this app — see `status`.
STATUS_PATH = RUNTIME_DIR / "browser-status"

#: Identifies the browser in /proc. The compositor starts it, so there is no
#: handle to keep — but it shares this container's PID namespace.
BROWSER_MARKER = "hmi_browser.py"

ROTATIONS = {0: "normal", 90: "90", 180: "180", 270: "270"}


def build_sway_config(
    display: Display,
    mode: Mode | None,
    rotation: int,
    hide_cursor: bool,
    browser_command: str,
) -> str:
    """A compositor config with exactly one job."""
    output_line = f"output {display.connector}"
    if mode:
        output_line += f" mode {mode}"
    output_line += f" transform {ROTATIONS.get(rotation, 'normal')} position 0 0"

    return "\n".join(
        [
            "# Generated by the Doover hmi-engine app. Edits will be overwritten.",
            output_line,
            # No X11 clients here, and without this sway logs a failure to
            # start Xwayland on every boot — noise in a support log.
            "xwayland disable",
            # Anything not covered by the page is black rather than undefined.
            f"output {display.connector} bg #000000 solid_color",
            "default_border none",
            "default_floating_border none",
            "hide_edge_borders --i3 both",
            "focus_follows_mouse no",
            *(["seat * hide_cursor 1"] if hide_cursor else []),
            # Anything the browser opens is still the kiosk; keep it fullscreen.
            'for_window [app_id=".*"] fullscreen enable',
            f"exec_always {browser_command}",
            "",
        ]
    )


def session_environment(display: Display, force_renderer: str = "auto") -> dict[str, str]:
    """Environment for the compositor and everything it launches.

    The renderer decision is the important one. wlroots' pixman renderer draws
    on the CPU into dumb buffers and needs no GPU userspace at all, which is the
    only thing that works on a board whose GPU has a vendor-only driver.
    """
    accelerated = display.accelerated
    if force_renderer == "gl":
        accelerated = True
    elif force_renderer == "pixman":
        accelerated = False

    env = {
        **os.environ,
        "WLR_BACKENDS": "drm",
        "WLR_DRM_DEVICES": display.device,
        "LIBSEAT_BACKEND": "seatd",
        "XDG_RUNTIME_DIR": str(RUNTIME_DIR),
        "GDK_BACKEND": "wayland",
        # WebKit's sandbox needs a user namespace the container may not grant.
        "WEBKIT_DISABLE_SANDBOX_THIS_IS_DANGEROUS": "1",
    }

    if not accelerated:
        env["WLR_RENDERER"] = "pixman"
        env["LIBGL_ALWAYS_SOFTWARE"] = "1"
        env["GALLIUM_DRIVER"] = "llvmpipe"
    if display.dri_path:
        env["LIBGL_DRIVERS_PATH"] = display.dri_path

    return env


def host_environment(compositor: HostCompositor, force_renderer: str = "auto") -> dict[str, str]:
    """Environment for a browser attaching to a compositor we did not start.

    Nothing here configures a display: the output, its mode, the rotation and
    the renderer all belong to whoever brought the compositor up. All this app
    contributes is a client, so all it sets is where to find the socket.
    """
    env = {
        **os.environ,
        "WAYLAND_DISPLAY": compositor.wayland_display,
        # Ours, not the host's — see `HostCompositor.wayland_display`. The
        # browser needs somewhere writable and the host's runtime dir is not
        # ours to write into.
        "XDG_RUNTIME_DIR": str(RUNTIME_DIR),
        "GDK_BACKEND": "wayland",
        # WebKit's sandbox needs a user namespace the container may not grant.
        "WEBKIT_DISABLE_SANDBOX_THIS_IS_DANGEROUS": "1",
    }

    # Only an explicit override. Mesa inside the container often cannot reach
    # the render node even where the host can, and says so loudly before
    # falling back on its own — but the host compositor is doing the
    # compositing either way, so guessing here would override a working GPU
    # for the sake of a quieter log.
    if force_renderer == "pixman":
        env["LIBGL_ALWAYS_SOFTWARE"] = "1"
        env["GALLIUM_DRIVER"] = "llvmpipe"

    return env


async def stop_conflicting_services(names: list[str]) -> list[str]:
    """Stop whatever else is drawing on the panel.

    Some vendor images run their own status screen on the framebuffer — ELPRO's
    Quantum ships two copies of a Qt splash — and it will happily repaint over
    anything this app draws. The host's init directory is bind-mounted in so the
    scripts can be stopped from here; disabling them at boot is left to the
    operator, because it is their device's behaviour being changed.
    """
    stopped = []
    for name in names:
        name = name.strip()
        if not name:
            continue
        script = Path("/host/etc/init.d") / name
        if not script.exists():
            log.info("Conflicting service %r not present; nothing to stop", name)
            continue
        try:
            proc = await asyncio.create_subprocess_exec(
                str(script), "stop",
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.STDOUT,
            )
            await asyncio.wait_for(proc.communicate(), timeout=15)
            log.info("Stopped conflicting service %r", name)
            stopped.append(name)
        except (OSError, asyncio.TimeoutError) as exc:
            log.warning("Could not stop %r: %s", name, exc)
    return stopped


PROC = Path("/proc")


def browser_pids(marker: str = BROWSER_MARKER, proc: Path = PROC) -> list[int]:
    """Find the browser by reading /proc.

    The compositor launches the browser via `exec_always`, so it is a grandchild
    this app never gets a handle to. Scanning /proc keeps the image free of
    procps just to send one signal.
    """
    pids = []
    try:
        entries = sorted(proc.iterdir())
    except OSError:
        return pids  # no /proc: not Linux, so not a device either
    for entry in entries:
        if not entry.name.isdigit():
            continue
        try:
            cmdline = (entry / "cmdline").read_bytes().decode(errors="replace")
        except OSError:
            continue  # the process exited while we were looking at it
        if marker in cmdline:
            pids.append(int(entry.name))
    return pids


def reload_page(marker: str = BROWSER_MARKER, proc: Path = PROC) -> int:
    """Ask the browser to re-fetch its page, and say how many heard.

    SIGHUP rather than a restart: the compositor stays up, the panel never goes
    black, and a page that is only stale — a widget bundle redeployed under it —
    is back within a frame or two.
    """
    signalled = 0
    for pid in browser_pids(marker, proc):
        try:
            os.kill(pid, signal.SIGHUP)
            signalled += 1
        except (ProcessLookupError, PermissionError) as exc:
            log.warning("Could not signal browser %s: %s", pid, exc)
    return signalled


class Session:
    """Owns whatever processes it takes to get the page on screen.

    Two shapes, one interface: `start` brings up seatd and sway and lets the
    compositor launch the browser, `start_hosted` runs the browser alone
    against a compositor the host already had. The watchdog above only asks
    whether the session is `running`, so it does not care which it got.
    """

    def __init__(self) -> None:
        self.seatd: asyncio.subprocess.Process | None = None
        self.sway: asyncio.subprocess.Process | None = None
        #: Only set in hosted mode. Otherwise the compositor owns the browser
        #: and this app never has a handle to it — see `browser_pids`.
        self.browser: asyncio.subprocess.Process | None = None

    @property
    def running(self) -> bool:
        proc = self.sway or self.browser
        return proc is not None and proc.returncode is None

    async def start(self, config: str, env: dict[str, str]) -> None:
        RUNTIME_DIR.mkdir(parents=True, exist_ok=True)
        RUNTIME_DIR.chmod(0o700)
        CONFIG_PATH.write_text(config)
        log.info("Compositor config:\n%s", config)

        if shutil.which("seatd") is None or shutil.which("sway") is None:
            raise RuntimeError("seatd and sway must be installed in the image")

        self.seatd = await asyncio.create_subprocess_exec(
            "seatd", stdout=asyncio.subprocess.DEVNULL, stderr=asyncio.subprocess.DEVNULL
        )
        # seatd has to own its socket before wlroots asks for a seat.
        await asyncio.sleep(2)

        # Inherit stdio rather than piping it. A pipe nothing drains fills its
        # buffer and then blocks the compositor — and the browser logs through
        # the same stream, so it would take the display down with it. Inheriting
        # puts both in `docker logs` where they are actually useful.
        self.sway = await asyncio.create_subprocess_exec(
            "sway", "-c", str(CONFIG_PATH),
            env=env,
        )
        log.info("Started compositor (pid %s)", self.sway.pid)

    async def start_hosted(self, browser_command: str, env: dict[str, str]) -> None:
        """Run only the browser, on a compositor that is already up.

        No seatd and no sway: there is nothing to become master of, and the
        browser is a direct child rather than a grandchild. `reload_page` still
        finds it the same way, by marker in /proc, so a new widget build
        reloads in place here too.
        """
        RUNTIME_DIR.mkdir(parents=True, exist_ok=True)
        RUNTIME_DIR.chmod(0o700)

        # Inherit stdio for the same reason the compositor does: a pipe nobody
        # drains eventually blocks the process writing to it.
        self.browser = await asyncio.create_subprocess_exec(
            *shlex.split(browser_command),
            env=env,
        )
        log.info(
            "Started browser (pid %s) on the host compositor at %s",
            self.browser.pid,
            env.get("WAYLAND_DISPLAY", "?"),
        )

    async def stop(self) -> None:
        for proc, name in ((self.browser, "browser"), (self.sway, "sway"), (self.seatd, "seatd")):
            if proc is None or proc.returncode is not None:
                continue
            try:
                proc.send_signal(signal.SIGTERM)
                await asyncio.wait_for(proc.wait(), timeout=10)
            except (asyncio.TimeoutError, ProcessLookupError):
                log.warning("%s did not exit; killing", name)
                try:
                    proc.kill()
                except ProcessLookupError:
                    pass
        self.sway = self.seatd = self.browser = None
